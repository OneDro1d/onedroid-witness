def _b64(b):
    return base64.b64encode(b).decode("ascii")


def _obj(slot, data, media_type="text/plain", name=None):
    return {"slot": slot, "media_type": media_type, "name": name or f"{slot}.txt", "data_b64": _b64(data),
            "sha256": hashlib.sha256(data).hexdigest()}


