def _judge_vectors():
    from .. import methods, record
    from ..methods import judge_supports as js
    temps = [{"claim_statement": s, "assertion": a, "statement": methods.render_statement("judge.supports", a, {"statement": s})}
             for s, a in JUDGE_TEMPLATES]
    cases = []
    for st, a, items, outputs, require in JUDGE_CASES:
        d = js.decide(st, a, items, outputs, require)
        cases.append({"statement": st, "assertion": a, "items": items, "outputs": outputs, "require": require,
                      "finding": d["finding"], "reason": d["reason"], "detail": d["detail"], "runs": d["runs"],
                      "injection_flags": d["injection_flags"], "input_sha256": d["input_sha256"],
                      "outcome": record.outcome_for(methods.finding_class("judge.supports", d["finding"]), a)})
    return {"prompt_sha256": js.prompt_sha256(), "templates": temps, "decide": cases}


def _check_judge(doc, lib, expect, outcome_for_verify):
    from .. import methods, record
    from ..methods import judge_supports as js
    j = doc.get("judge")
    if not j:
        expect("judge vectors present", False, True)
        return
    expect("judge prompt_sha256 witness", js.prompt_sha256(), j["prompt_sha256"])
    expect("judge prompt_sha256 tarball", lib.judge_supports.prompt_sha256(), j["prompt_sha256"])
    for i, t in enumerate(j["templates"]):
        for side, mod in (("witness", methods), ("tarball", lib)):
            expect(f"judge templates[{i}] {side}", mod.render_statement("judge.supports", t["assertion"],
                                                                        {"statement": t["claim_statement"]}), t["statement"])
    for i, c in enumerate(j["decide"]):
        for side, mod, outcome_for in (("witness", js, record.outcome_for), ("tarball", lib.judge_supports, outcome_for_verify)):
            d = mod.decide(c["statement"], c["assertion"], c["items"], c["outputs"], c["require"])
            fclass = (methods if side == "witness" else lib).finding_class("judge.supports", d["finding"])
            got = {"finding": d["finding"], "reason": d["reason"], "detail": d["detail"], "runs": d["runs"],
                   "injection_flags": d["injection_flags"], "input_sha256": d["input_sha256"],
                   "outcome": outcome_for(fclass, c["assertion"])}
            for k in got:
                expect(f"judge decide[{i}] {side} {k}", got[k], c[k])
            expect(f"judge decide[{i}] {side} input", hashlib.sha256(
                mod.build_input(c["statement"], c["assertion"], c["items"]).encode("utf-8")).hexdigest(), c["input_sha256"])


class _Clock:
    def __init__(self, t):
        self.t = t

    def __call__(self):
        return self.t


def _record_envelopes():
    """A public record (with an agent signature) and a private record (fixed salt), signed by the vector key, plus the key list
    they verify under and the agent key."""
    from .. import attempts, crypto, ids, jcs, methods, record, signer, storage, tarball
    from ..schemas import CLAIM_TYPE
    from ..service import RUNTIME, iso
    clock = _Clock(T0)
    st = storage.MemoryStorage()
    key_list = signer.keylist_init(st, SEED, KEY_ID, WITNESS_ID, clock=clock)
    clock.t = T0 + 60
    core = signer.SignerCore(SEED, KEY_ID, WITNESS_ID, st, clock=clock)
    claim = {"method": "quote.in-source", "method_major": 1, "params": {"quote": "not a judge of truth"}, "assertion": True,
             "statement": None}
    src = hashlib.sha256(SOURCE).hexdigest()
    evidence = [{"slot": "source", "kind": "object", "sha256": src, "media_type": "text/plain", "name": "source.txt"}]
    m = methods.get("quote.in-source")
    res = methods.run(m.id, claim["params"], {"source": dict(evidence[0], data=SOURCE)})
    nonce, agent_time = "nonce-vector-0001", iso(clock())
    agent_pub = crypto.ed25519_public(AGENT_SEED)
    msg = jcs.canonical({"witness_id": WITNESS_ID, "claim_id": ids.claim_id(claim), "evidence": [src], "nonce": nonce,
                         "agent_time": agent_time})
    agent = {"agent_key_id": "ak_vector", "agent": "agt_vector", "public_key": _b64(agent_pub)}
    submitter = {"account": "acct_vector", "agent": agent["agent"], "agent_key_id": agent["agent_key_id"],
                 "agent_sig": _b64(crypto.ed25519_sign(AGENT_SEED, msg)), "nonce": nonce, "agent_time": agent_time}
    out = []
    for vis in ("public", "private"):
        pred = record.public_predicate(
            claim, m.render(True, res.vars), evidence,
            {"id": m.id, "version": m.version, "code_sha256": tarball.methods_code_sha256(), "runtime": RUNTIME},
            res.finding, res.reason, res.detail, m.limits, attempts.attempt_field({"SUPPORTED": 0, "NOT_SUPPORTED": 0, "CANNOT_WITNESS": 0}),
            submitter, {"accept_untrusted": False, "allow_provider": False, "panel": 1}, iso(clock()),
            {"id": WITNESS_ID, "key_id": KEY_ID, "key_list_seq": 1})
        stmt, disclosure = record.build(pred, vis, label="vector label" if vis == "private" else None, salt=SALT)
        env = core.sign(CLAIM_TYPE, stmt)["envelope"]
        payload = base64.b64decode(env["payload"])
        out.append({"visibility": vis, "seed_hex": SEED.hex(), "key_id": KEY_ID, "public_b64": _b64(crypto.ed25519_public(SEED)),
                    "payload_b64": env["payload"], "record_id": ids.record_id(payload), "envelope": env, "key_list": key_list,
                    "disclosure": disclosure, "agent_key": agent, "evidence_b64": [_b64(SOURCE)]})
    return out


def generate():
    from .. import attempts, canon, ids, jcs, methods, record
    doc = {"about": "claim witness test vectors (SPEC TS-23); regenerate with python3 -m claim_witness.vectors --write",
           "jcs": [{"input": v, "canonical": jcs.canonical(v).decode("utf-8")} for v in JCS_CASES],
           "canon1": [{"input": t, "media_type": mt, "layer": layer, "output": canon.canon1(t, mt, layer=layer)}
                      for t, mt, layer in CANON_CASES]}
    claims = [{"method": mid, "method_major": 1, "params": p, "assertion": a, "statement": None}
              for mid, p, a, _ in TEMPLATE_CASES[::2]]
    doc["claim_id"] = [{"claim": c, "canonical": jcs.canonical(c).decode("utf-8"), "claim_id": ids.claim_id(c)} for c in claims]
    payloads = [jcs.canonical({"x": 1}), jcs.canonical({"predicate": {"outcome": "SUPPORTED"}, "subject": []})]
    doc["record_id"] = [{"payload_b64": _b64(p), "record_id": ids.record_id(p), "leaf_hash": ids.leaf_hash(p)} for p in payloads]
    bodies = [{"visibility": "private", "label": None}, {"visibility": "private", "label": "my words", "claim": claims[0]}]
    doc["commitments"] = [{"salt_hex": SALT.hex(), "salt_b64url": ids.b64url(SALT), "claim": c, "body": b,
                           "claim_commitment": ids.claim_commitment(SALT, c), "body_commitment": ids.body_commitment(SALT, b)}
                          for c, b in zip(claims[:2], bodies)]
    doc["attempt_tag"] = [{"key_hex": (b"K" * 32).hex(), "claim": claims[0], "objects": ["b" * 64, "a" * 64], "urls": [],
                           "method": "match.exact", "account": "acct_a",
                           "tag": attempts.attempt_tag(b"K" * 32, claims[0], ["b" * 64, "a" * 64], [], "match.exact", "acct_a")}]
    temps = []
    for mid, params, assertion, ev in TEMPLATE_CASES:
        res = _run_witness(mid, params, ev)
        temps.append({"method": mid, "params": params, "assertion": assertion, "evidence": ev, "finding": res.finding,
                      "reason": res.reason, "detail": res.detail, "failing_tests": res.failing_tests,
                      "outcome": record.outcome_for(methods.finding_class(mid, res.finding), assertion),
                      "statement": methods.render_statement(mid, assertion, res.vars), "limits": methods.get(mid).limits})
    doc["templates"] = temps
    doc["judge"] = _judge_vectors()
    doc["envelope"] = _record_envelopes()
    return doc


def _evidence_of(ev):
    return {e["slot"]: {"slot": e["slot"], "kind": "object", "sha256": e["sha256"], "media_type": e["media_type"], "name": e["name"],
                        "data": base64.b64decode(e["data_b64"])} for e in ev}


def _run_witness(mid, params, ev):
    from .. import methods
    return methods.run(mid, params, _evidence_of(ev))


def check(doc, out):
    """Every vector against the witness and against witness-verify; returns the number of failures."""
    from .. import attempts, canon, dsse, ids, jcs, methods, record, tarball, verify
    fails, n = [], 0

    def expect(name, got, want):
        nonlocal n
        n += 1
        if got != want:
            fails.append(name)
            print(f"FAIL {name}: got {str(got)[:160]!r}, want {str(want)[:160]!r}", file=out)

    tar = tarball.build_methods_tarball()
    lib = verify._load_methods(tar)
    for i, v in enumerate(doc.get("jcs") or []):
        expect(f"jcs[{i}] witness", jcs.canonical(v["input"]).decode("utf-8"), v["canonical"])
        expect(f"jcs[{i}] verify", verify.canonical(v["input"]).decode("utf-8"), v["canonical"])
        expect(f"jcs[{i}] is_canonical", jcs.is_canonical(v["canonical"].encode("utf-8")), True)
    for i, v in enumerate(doc.get("canon1") or []):
        expect(f"canon1[{i}] witness", canon.canon1(v["input"], v["media_type"], layer=v["layer"]), v["output"])
        expect(f"canon1[{i}] tarball", lib.canon.canon1(v["input"], v["media_type"], layer=v["layer"]), v["output"])
    for i, v in enumerate(doc.get("claim_id") or []):
        expect(f"claim_id[{i}] canonical", jcs.canonical(v["claim"]).decode("utf-8"), v["canonical"])
        expect(f"claim_id[{i}] witness", ids.claim_id(v["claim"]), v["claim_id"])
        expect(f"claim_id[{i}] verify", verify.claim_id(v["claim"]), v["claim_id"])
    for i, v in enumerate(doc.get("record_id") or []):
        p = base64.b64decode(v["payload_b64"])
        expect(f"record_id[{i}] witness", ids.record_id(p), v["record_id"])
        expect(f"record_id[{i}] verify", verify.sha256_hex(p), v["record_id"])
        expect(f"record_id[{i}] leaf", ids.leaf_hash(p), v["leaf_hash"])
    for i, v in enumerate(doc.get("commitments") or []):
        salt = bytes.fromhex(v["salt_hex"])
        expect(f"commitments[{i}] salt", ids.b64url_decode(v["salt_b64url"]), salt)
        expect(f"commitments[{i}] claim witness", ids.claim_commitment(salt, v["claim"]), v["claim_commitment"])
        expect(f"commitments[{i}] claim verify", verify.claim_commitment(salt, v["claim"]), v["claim_commitment"])
        expect(f"commitments[{i}] body witness", ids.body_commitment(salt, v["body"]), v["body_commitment"])
        expect(f"commitments[{i}] body verify", verify.body_commitment(salt, v["body"]), v["body_commitment"])
    for i, v in enumerate(doc.get("attempt_tag") or []):
        expect(f"attempt_tag[{i}]", attempts.attempt_tag(bytes.fromhex(v["key_hex"]), v["claim"], v["objects"], v["urls"],
                                                          v["method"], v["account"]), v["tag"])
    for i, v in enumerate(doc.get("templates") or []):
        name = f"templates[{i}] {v['method']} {v['assertion']}"
        for side, mod, outcome_for in (("witness", methods, record.outcome_for), ("tarball", lib, verify.outcome_for)):
            res = mod.run(v["method"], v["params"], _evidence_of(v["evidence"]))
            got = {"finding": res.finding, "reason": res.reason, "detail": res.detail, "failing_tests": res.failing_tests,
                   "outcome": outcome_for(mod.finding_class(v["method"], res.finding), v["assertion"]),
                   "statement": mod.render_statement(v["method"], v["assertion"], res.vars), "limits": mod.get(v["method"]).limits}
            for k in got:
                expect(f"{name} {side} {k}", got[k], v[k])
    _check_judge(doc, lib, expect, verify.outcome_for)
    for i, v in enumerate(doc.get("envelope") or []):
        name = f"envelope[{i}] {v['visibility']}"
        seed = bytes.fromhex(v["seed_hex"])
        payload = base64.b64decode(v["payload_b64"])
        expect(f"{name} witness sign", dsse.sign(payload, [(v["key_id"], seed)]), v["envelope"])
        expect(f"{name} verify public key", _b64(verify.ed25519_public_pure(seed)), v["public_b64"])
        expect(f"{name} verify signature", verify._verify_sig(v["envelope"], v["key_id"], base64.b64decode(v["public_b64"])), True)
        expect(f"{name} record id", ids.record_id(payload), v["record_id"])
        buf = io.StringIO()
        r = verify.Report(buf)
        files = [base64.b64decode(x) for x in v["evidence_b64"]]
        verify.run_checks(r, v["envelope"], v["key_list"], False, v["disclosure"], v["agent_key"], files, tar, v["record_id"])
        expect(f"{name} witness-verify", [x for x in buf.getvalue().splitlines() if x.startswith("FAIL")], [])
        for check_name in ("signature", "record-id", "method-rerun", "agent-signature"):
            expect(f"{name} witness-verify {check_name}", f"PASS {check_name}" in buf.getvalue(), True)
    print(f"ed25519 (verify side): {'pure-python' if verify._backend() is None else 'cryptography'}", file=out)
    if fails:
        print(f"FAIL {len(fails)} of {n} checks", file=out)
        return len(fails)
    print(f"all vectors reproduce ({n} checks)", file=out)
    return 0
