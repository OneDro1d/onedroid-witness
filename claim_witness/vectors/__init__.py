def _obs_of(o):
    return {"slot": o["slot"], "kind": "observation", "id": o["id"], "manifest": o["manifest"],
            "files": {n: base64.b64decode(b) for n, b in o["files_b64"].items()}}


def _evidence_of(ev):
    out = {}
    for e in ev:
        if e.get("kind") == "observation":
            out[e["slot"]] = _obs_of(e)
        elif e.get("kind") == "url" and "attempts" not in e:
            out[e["slot"]] = dict(e)  # a url the witness does not fetch (post.by-author: method-not-applicable)
        elif e.get("kind") == "url":
            out[e["slot"]] = dict(e, attempts=[a if "failure" in a else {"observation": _obs_of(a["observation"])}
                                               for a in e["attempts"]])
        else:
            item = {"slot": e["slot"], "kind": "object", "sha256": e["sha256"], "media_type": e["media_type"], "name": e["name"],
                    "data": base64.b64decode(e["data_b64"])}
            if "ocr_text" in e:
                item["ocr_text"] = e["ocr_text"]
            if "ocr_readability" in e:
                item["ocr_readability"] = e["ocr_readability"]
            out[e["slot"]] = item
    return out


def _run_witness(mid, params, ev):
    from .. import methods
    return methods.run(mid, params, _evidence_of(ev))


def check(doc, out):
    """Every vector against the witness and against witness-verify; returns the number of failures."""
    from .. import attempts, canon, crypto, dsse, ids, jcs, methods, record, tarball, verify
    fails, n = [], 0

    def expect(name, got, want):
        nonlocal n
        n += 1
        if got != want:
            fails.append(name)
            print(f"FAIL {name}: got {str(got)[:160]!r}, want {str(want)[:160]!r}", file=out)

    tar = tarball.build_methods_tarball()
    lib = verify._load_methods(tar)
    for i, v in enumerate(doc.get("jcs") or []):
        expect(f"jcs[{i}] witness", jcs.canonical(v["input"]).decode("utf-8"), v["canonical"])
        expect(f"jcs[{i}] verify", verify.canonical(v["input"]).decode("utf-8"), v["canonical"])
        expect(f"jcs[{i}] is_canonical", jcs.is_canonical(v["canonical"].encode("utf-8")), True)
    for i, v in enumerate(doc.get("canon1") or []):
        expect(f"canon1[{i}] witness", canon.canon1(v["input"], v["media_type"], layer=v["layer"]), v["output"])
        expect(f"canon1[{i}] tarball", lib.canon.canon1(v["input"], v["media_type"], layer=v["layer"]), v["output"])
    for i, v in enumerate(doc.get("claim_id") or []):
        expect(f"claim_id[{i}] canonical", jcs.canonical(v["claim"]).decode("utf-8"), v["canonical"])
        expect(f"claim_id[{i}] witness", ids.claim_id(v["claim"]), v["claim_id"])
        expect(f"claim_id[{i}] verify", verify.claim_id(v["claim"]), v["claim_id"])
    for i, v in enumerate(doc.get("record_id") or []):
        p = base64.b64decode(v["payload_b64"])
        expect(f"record_id[{i}] witness", ids.record_id(p), v["record_id"])
        expect(f"record_id[{i}] verify", verify.sha256_hex(p), v["record_id"])
        expect(f"record_id[{i}] leaf", ids.leaf_hash(p), v["leaf_hash"])
    for i, v in enumerate(doc.get("commitments") or []):
        salt = bytes.fromhex(v["salt_hex"])
        expect(f"commitments[{i}] salt", ids.b64url_decode(v["salt_b64url"]), salt)
        expect(f"commitments[{i}] claim witness", ids.claim_commitment(salt, v["claim"]), v["claim_commitment"])
        expect(f"commitments[{i}] claim verify", verify.claim_commitment(salt, v["claim"]), v["claim_commitment"])
        expect(f"commitments[{i}] body witness", ids.body_commitment(salt, v["body"]), v["body_commitment"])
        expect(f"commitments[{i}] body verify", verify.body_commitment(salt, v["body"]), v["body_commitment"])
    for i, v in enumerate(doc.get("attempt_tag") or []):
        expect(f"attempt_tag[{i}]", attempts.attempt_tag(bytes.fromhex(v["key_hex"]), v["claim"], v["objects"], v["urls"],
                                                          v["method"], v["account"]), v["tag"])
    for i, v in enumerate(doc.get("templates") or []):
        name = f"templates[{i}] {v['method']} {v['assertion']}"
        for side, mod, outcome_for in (("witness", methods, record.outcome_for), ("tarball", lib, verify.outcome_for)):
            res = mod.run(v["method"], v["params"], _evidence_of(v["evidence"]))
            got = {"finding": res.finding, "reason": res.reason, "detail": res.detail, "failing_tests": res.failing_tests,
                   "outcome": outcome_for(mod.finding_class(v["method"], res.finding), v["assertion"]),
                   "statement": mod.render_statement(v["method"], v["assertion"], res.vars), "limits": mod.get(v["method"]).limits}
            for k in got:
                expect(f"{name} {side} {k}", got[k], v[k])
    _check_judge(doc, lib, expect, verify.outcome_for)
    for i, v in enumerate(doc.get("record_methods") or []):
        name = f"record_methods[{i}] {v['method']} ({v['name']})"
        for side, mod, ed, outcome_for in (("witness", methods, crypto.ed25519_verify, record.outcome_for),
                                           ("tarball", lib, verify.ed25519_verify, verify.outcome_for)):
            res = _run_record_method(mod, ed, v)
            got = {"finding": res.finding, "reason": res.reason, "detail": res.detail,
                   "outcome": outcome_for(mod.finding_class(v["method"], res.finding), v["assertion"]),
                   "statement": mod.render_statement(v["method"], v["assertion"], res.vars), "limits": mod.get(v["method"]).limits}
            for k in got:
                expect(f"{name} {side} {k}", got[k], v[k])
        if v["method"] == "record.valid" and v["reason"] != "unreadable":
            # witness-verify reaches the same verdict on the same inputs: a FAIL line exactly when the record is invalid
            buf = io.StringIO()
            key_list = json.loads(base64.b64decode(v["objects"][0]["data_b64"]))
            verify.run_checks(verify.Report(buf), v["record"]["envelope"], key_list, False, None, None, [], None, v["record"]["id"],
                              v["record"]["seal"])
            expect(f"{name} witness-verify agrees", any(x.startswith("FAIL") for x in buf.getvalue().splitlines()),
                   v["finding"] == "record-invalid")
    for i, c in enumerate(JCS_CASES):
        expect(f"jcs[{i}] tarball recordcheck", lib.recordcheck.canonical(c).decode("utf-8"), jcs.canonical(c).decode("utf-8"))
    for mid, th in (doc.get("thresholds") or {}).items():
        expect(f"thresholds {mid} witness", methods.get(mid).thresholds, th)
        expect(f"thresholds {mid} tarball", lib.get(mid).thresholds, th)
    from .. import observation
    for i, v in enumerate(doc.get("observation") or []):
        name = f"observation[{i}] {v['visibility']}"
        files = {n: base64.b64decode(b) for n, b in v["capture_files_b64"].items()}
        pred, files2 = observation.from_capture(v["capture_manifest"], files, v["visibility"])
        expect(f"{name} text.canonical.txt witness", files2["text.canonical.txt"].decode("utf-8"), v["text_canonical"])
        expect(f"{name} text.canonical.txt tarball",
               lib.canon.canon1(files["rendered.html"], "text/html", layer="rendered"), v["text_canonical"])
        stmt, disclosure = observation.statement(pred, salt=bytes.fromhex(v["salt_hex"]))
        expect(f"{name} statement", stmt, v["statement"])
        raw = jcs.canonical(stmt)
        expect(f"{name} payload", _b64(raw), v["payload_b64"])
        expect(f"{name} id witness", ids.record_id(raw), v["observation_id"])
        expect(f"{name} id verify", verify.sha256_hex(verify.canonical(v["statement"])), v["observation_id"])
        if v["visibility"] == "public":
            expect(f"{name} manifest digest verify", verify.sha256_hex(verify.canonical(v["statement"]["predicate"])),
                   v["statement"]["subject"][0]["digest"]["sha256"])
        else:
            expect(f"{name} body commitment verify", verify.body_commitment(bytes.fromhex(v["salt_hex"]), v["disclosure"]["body"]),
                   v["statement"]["predicate"]["body_commitment"])
    for i, v in enumerate(doc.get("envelope") or []):
        name = f"envelope[{i}] {v['visibility']}"
        seed = bytes.fromhex(v["seed_hex"])
        payload = base64.b64decode(v["payload_b64"])
        expect(f"{name} witness sign", dsse.sign(payload, [(v["key_id"], seed)]), v["envelope"])
        expect(f"{name} verify public key", _b64(verify.ed25519_public_pure(seed)), v["public_b64"])
        expect(f"{name} verify signature", verify._verify_sig(v["envelope"], v["key_id"], base64.b64decode(v["public_b64"])), True)
        expect(f"{name} record id", ids.record_id(payload), v["record_id"])
        buf = io.StringIO()
        r = verify.Report(buf)
        files = [base64.b64decode(x) for x in v["evidence_b64"]]
        verify.run_checks(r, v["envelope"], v["key_list"], False, v["disclosure"], v["agent_key"], files, tar, v["record_id"])
        expect(f"{name} witness-verify", [x for x in buf.getvalue().splitlines() if x.startswith("FAIL")], [])
        for check_name in ("signature", "record-id", "method-rerun", "agent-signature"):
            expect(f"{name} witness-verify {check_name}", f"PASS {check_name}" in buf.getvalue(), True)
    from .. import merkle, sealer
    from ..signer import BATCH_PAYLOAD_TYPE
    sv = doc.get("seal")
    if not sv:
        expect("seal vectors present", False, True)
    else:
        payloads = [base64.b64decode(x) for x in sv["payloads_b64"]]
        leaves = [ids.leaf_hash(x) for x in payloads]
        expect("seal leaves witness", leaves, sv["leaves"])
        expect("seal leaves verify", [verify.sha256_hex(b"\x00" + x) for x in payloads], sv["leaves"])
        expect("seal root witness", merkle.root(leaves), sv["root"])
        expect("seal paths witness", merkle.paths(leaves), sv["paths"])
        for i, path in enumerate(sv["paths"]):
            expect(f"seal path[{i}] witness", merkle.root_from_path(leaves[i], i, len(leaves), path), sv["root"])
            expect(f"seal path[{i}] verify", verify.merkle_root_from_path(leaves[i], i, len(leaves), path), sv["root"])
        hdr = sv["batch_header"]
        unsigned = {k: v for k, v in hdr.items() if k != "sig"}
        expect("seal header signature witness", dsse.sign(jcs.canonical(unsigned), [(KEY_ID, SEED)], BATCH_PAYLOAD_TYPE)
               ["signatures"][0]["sig"], hdr["sig"])
        expect("seal header signature verify", verify.ed25519_verify(verify.ed25519_public_pure(SEED), base64.b64decode(hdr["sig"]),
                                                                     verify.pae(BATCH_PAYLOAD_TYPE, verify.canonical(unsigned))), True)
        expect("seal over witness", "sha256:" + sealer.over_of(hdr), sv["over"])
        expect("seal over verify", "sha256:" + verify.sha256_hex(verify.canonical(hdr)), sv["over"])
        expect("seal notary over", sv["notary"]["over"], sv["over"])
        for i, (v, seal) in enumerate(zip(doc.get("envelope") or [], sv["seals"])):
            buf = io.StringIO()
            r = verify.Report(buf)
            verify.run_checks(r, v["envelope"], v["key_list"], False, v["disclosure"], v["agent_key"],
                              [base64.b64decode(x) for x in v["evidence_b64"]], tar, v["record_id"], seal)
            text = buf.getvalue()
            expect(f"seal envelope[{i}] witness-verify no FAIL", [x for x in text.splitlines() if x.startswith("FAIL")], [])
            expect(f"seal envelope[{i}] witness-verify PASS seal", "PASS seal:" in text, True)
            expect(f"seal envelope[{i}] witness-verify PASS key-validity", "PASS key-validity" in text, True)
            bad = json.loads(json.dumps(seal))
            bad["path"][0] = ("f" if bad["path"][0][0] != "f" else "e") + bad["path"][0][1:]
            buf = io.StringIO()
            verify.run_checks(verify.Report(buf), v["envelope"], v["key_list"], False, v["disclosure"], None, [], None,
                              v["record_id"], bad)
            expect(f"seal envelope[{i}] one path hash changed: FAIL seal", "FAIL seal:" in buf.getvalue(), True)
        print(f"seal vectors: {len(leaves)} leaves, root {sv['root'][:16]}..., {len(sv['seals'])} sealed records", file=out)
    _check_own_seal(doc, tar, expect, out)  # own model key (C2)
    print(f"ed25519 (verify side): {'pure-python' if verify._backend() is None else 'cryptography'}", file=out)
    if fails:
        print(f"FAIL {len(fails)} of {n} checks", file=out)
        return len(fails)
    print(f"all vectors reproduce ({n} checks)", file=out)
    return 0
