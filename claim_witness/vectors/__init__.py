"""Test vectors (SPEC §2.0, TS-23): RFC 8785 with integers only, canon/1, claim ids, record ids and leaves, commitments, the
per-method templates with their findings and outcomes, judge.supports (its templates, the prompt's sha256, and the model input
and decision over fixed model outputs: B6), and signed envelopes (a public and a private record, with the key
list they verify under). vectors.json is generated by `python3 -m claim_witness.vectors --write` and checked by `--check`.

Every vector is reproduced twice: by the witness's own modules (jcs, ids, canon, methods, record, dsse, signer) and by
witness-verify (claim_witness/verify.py, standard library only, with the methods loaded from the reproducible tarball the
records' code_sha256 names). WITNESS_VERIFY_PURE=1 makes the verify side use its pure-Python Ed25519.
"""
