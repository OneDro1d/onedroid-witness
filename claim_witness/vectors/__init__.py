def _judge_vectors():
    from .. import methods, record
    from ..methods import judge_supports as js
    temps = [{"claim_statement": s, "assertion": a, "statement": methods.render_statement("judge.supports", a, {"statement": s})}
             for s, a in JUDGE_TEMPLATES]
    cases = []
    for st, a, items, outputs, require in JUDGE_CASES:
        d = js.decide(st, a, items, outputs, require)
        cases.append({"statement": st, "assertion": a, "items": items, "outputs": outputs, "require": require,
                      "finding": d["finding"], "reason": d["reason"], "detail": d["detail"], "runs": d["runs"],
                      "injection_flags": d["injection_flags"], "input_sha256": d["input_sha256"],
                      "outcome": record.outcome_for(methods.finding_class("judge.supports", d["finding"]), a)})
    return {"prompt_sha256": js.prompt_sha256(), "templates": temps, "decide": cases}


def _check_judge(doc, lib, expect, outcome_for_verify):
    from .. import methods, record
    from ..methods import judge_supports as js
    j = doc.get("judge")
    if not j:
        expect("judge vectors present", False, True)
        return
    expect("judge prompt_sha256 witness", js.prompt_sha256(), j["prompt_sha256"])
    expect("judge prompt_sha256 tarball", lib.judge_supports.prompt_sha256(), j["prompt_sha256"])
    for i, t in enumerate(j["templates"]):
        for side, mod in (("witness", methods), ("tarball", lib)):
            expect(f"judge templates[{i}] {side}", mod.render_statement("judge.supports", t["assertion"],
                                                                        {"statement": t["claim_statement"]}), t["statement"])
    for i, c in enumerate(j["decide"]):
        for side, mod, outcome_for in (("witness", js, record.outcome_for), ("tarball", lib.judge_supports, outcome_for_verify)):
            d = mod.decide(c["statement"], c["assertion"], c["items"], c["outputs"], c["require"])
            fclass = (methods if side == "witness" else lib).finding_class("judge.supports", d["finding"])
            got = {"finding": d["finding"], "reason": d["reason"], "detail": d["detail"], "runs": d["runs"],
                   "injection_flags": d["injection_flags"], "input_sha256": d["input_sha256"],
                   "outcome": outcome_for(fclass, c["assertion"])}
            for k in got:
                expect(f"judge decide[{i}] {side} {k}", got[k], c[k])
            expect(f"judge decide[{i}] {side} input", hashlib.sha256(
                mod.build_input(c["statement"], c["assertion"], c["items"]).encode("utf-8")).hexdigest(), c["input_sha256"])


class _Clock:
    def __init__(self, t):
        self.t = t

    def __call__(self):
        return self.t


def _record_envelopes():
    """A public record (with an agent signature) and a private record (fixed salt), signed by the vector key, plus the key list
    they verify under and the agent key."""
    from .. import attempts, crypto, ids, jcs, methods, record, signer, storage, tarball
    from ..schemas import CLAIM_TYPE
    from ..service import RUNTIME, iso
    clock = _Clock(T0)
    st = storage.MemoryStorage()
    key_list = signer.keylist_init(st, SEED, KEY_ID, WITNESS_ID, clock=clock)
    clock.t = T0 + 60
    core = signer.SignerCore(SEED, KEY_ID, WITNESS_ID, st, clock=clock)
    claim = {"method": "quote.in-source", "method_major": 1, "params": {"quote": "not a judge of truth"}, "assertion": True,
             "statement": None}
    src = hashlib.sha256(SOURCE).hexdigest()
    evidence = [{"slot": "source", "kind": "object", "sha256": src, "media_type": "text/plain", "name": "source.txt"}]
    m = methods.get("quote.in-source")
    res = methods.run(m.id, claim["params"], {"source": dict(evidence[0], data=SOURCE)})
    nonce, agent_time = "nonce-vector-0001", iso(clock())
    agent_pub = crypto.ed25519_public(AGENT_SEED)
    msg = jcs.canonical({"witness_id": WITNESS_ID, "claim_id": ids.claim_id(claim), "evidence": [src], "nonce": nonce,
                         "agent_time": agent_time})
    agent = {"agent_key_id": "ak_vector", "agent": "agt_vector", "public_key": _b64(agent_pub)}
    submitter = {"account": "acct_vector", "agent": agent["agent"], "agent_key_id": agent["agent_key_id"],
                 "agent_sig": _b64(crypto.ed25519_sign(AGENT_SEED, msg)), "nonce": nonce, "agent_time": agent_time}
    out = []
    for vis in ("public", "private"):
        pred = record.public_predicate(
            claim, m.render(True, res.vars), evidence,
            {"id": m.id, "version": m.version, "code_sha256": tarball.methods_code_sha256(), "runtime": RUNTIME},
            res.finding, res.reason, res.detail, m.limits, attempts.attempt_field({"SUPPORTED": 0, "NOT_SUPPORTED": 0, "CANNOT_WITNESS": 0}),
            submitter, {"accept_untrusted": False, "allow_provider": False, "panel": 1}, iso(clock()),
            {"id": WITNESS_ID, "key_id": KEY_ID, "key_list_seq": 1})
        stmt, disclosure = record.build(pred, vis, label="vector label" if vis == "private" else None, salt=SALT)
        env = core.sign(CLAIM_TYPE, stmt)["envelope"]
        payload = base64.b64decode(env["payload"])
        out.append({"visibility": vis, "seed_hex": SEED.hex(), "key_id": KEY_ID, "public_b64": _b64(crypto.ed25519_public(SEED)),
                    "payload_b64": env["payload"], "record_id": ids.record_id(payload), "envelope": env, "key_list": key_list,
                    "disclosure": disclosure, "agent_key": agent, "evidence_b64": [_b64(SOURCE)]})
    return out


