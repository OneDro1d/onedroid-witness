def _q(text, phrase, source=0):
    i = text.find(phrase)
    return {"source": source, "start": i, "end": i + len(phrase), "text": phrase}


def _ans(finding, quotes=()):
    return json.dumps({"finding": finding, "quotes": list(quotes)}, sort_keys=True)


